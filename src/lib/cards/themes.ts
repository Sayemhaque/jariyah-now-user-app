export const cardThemes: CardTheme[] = [...signatureThemes, ...familyThemes(colourFamilies)]

export const findCardTheme = (key: string) => cardThemes.find((t) => t.key === key) ?? cardThemes[0]!

export const lightCardThemes = cardThemes.filter((t) => t.light)
export const darkCardThemes = cardThemes.filter((t) => !t.light)

export const alternatingCardThemes = Array.from({ length: Math.max(lightCardThemes.length, darkCardThemes.length) * 2 }, (_, i) =>
  (i % 2 === 0 ? lightCardThemes : darkCardThemes)[Math.floor(i / 2) % (i % 2 === 0 ? lightCardThemes : darkCardThemes).length]!,
)
